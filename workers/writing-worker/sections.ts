export type ParsedSection = { heading: string | null; body: string };

/**
 * Split an article into (preamble incl. H1 + intro) + H2-keyed sections,
 * preserving order. The preamble entry has heading null.
 */
export function splitIntoSections(markdown: string): ParsedSection[] {
  const lines = markdown.split("\n");
  const sections: ParsedSection[] = [];
  let current: ParsedSection = { heading: null, body: "" };

  for (const line of lines) {
    if (line.startsWith("## ")) {
      sections.push(current);
      current = { heading: line.replace(/^##\s+/, "").trim(), body: `${line}\n` };
    } else {
      current.body += `${line}\n`;
    }
  }
  sections.push(current);
  return sections.filter((section) => section.heading !== null || section.body.trim().length > 0);
}

export function joinSections(sections: ParsedSection[]): string {
  return sections
    .map((section) => section.body.trim())
    .filter(Boolean)
    .join("\n\n")
    .trim();
}

/** Case/format-insensitive H2 lookup for judge-provided section names. */
export function findSection(sections: ParsedSection[], heading: string): ParsedSection | undefined {
  const wanted = normalizeHeading(heading);
  return sections.find((section) => {
    if (section.heading === null) return false;
    const have = normalizeHeading(section.heading);
    return have === wanted || have.includes(wanted) || wanted.includes(have);
  });
}
