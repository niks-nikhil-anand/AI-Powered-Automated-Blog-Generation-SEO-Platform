/**
 * Section-by-section writing (ENHANCEMENT_IMPLEMENTATION_PLAN.md Task 5).
 * Instead of one monolithic 8k-token completion (which degrades
 * mid-document and must be wholly regenerated on any QA failure), the
 * article is decomposed into the mandatory section skeleton, each section
 * generated by an independent Flash-class call, retried individually, and
 * cached in Redis so a stage-level retry only regenerates what failed.
 *
 * The section plan derives from the MANDATORY skeleton (not the outline's
 * free-form sections) so sectioned output is structurally guaranteed to
 * satisfy the writing gate and the quality scorer's requiredSections -
 * outline bullets/FAQs are merged in where they align.
 */

export type SectionKind =
  | "intro"
  | "toc"
  | "generic"
  | "subsections"
  | "steps"
  | "table"
  | "numbered"
  | "bullets"
  | "faq"
  | "cta";

export type SubsectionSpec = {
  heading: string;
  discuss?: string[];
  keywords?: string[];
};

export type ComparisonTableSpec = {
  columns: string[];
  rows: string[];
  instructions?: string;
};

export type SectionSpec = {
  /** H2 text; null only for the heading-less intro. */
  heading: string | null;
  kind: SectionKind;
  intent: string;
  bullets: string[];
  wordTarget: number;
  subsections?: SubsectionSpec[];
  comparisonTable?: ComparisonTableSpec;
  /**
   * Brief-supplied section directives (outlineJson.sections[]): the question
   * this section answers, what it must not do, extra requirements, the
   * evidence bar, an illustrative scenario, a required output format, and a
   * link the section has to carry.
   */
  readerQuestion?: string;
  avoid?: string[];
  requirements?: string[];
  evidenceRequirements?: string[];
  practicalExample?: string;
  format?: string;
  requiredInternalLink?: { url: string; anchor?: string };
  /** FAQ questions that must be emitted as H3 entries with answers. */
};

export type SectionArticleContext = {
  title: string;
  topic: string;
  description: string;
  plan?: {
    searchIntent: string;
    audience: string;
    angle: string;
    primaryKeyword: string;
    secondaryKeywords: unknown;
    competitorNotes: unknown;
  };
  outline?: { sections: unknown; faqs: unknown };
  sources?: GroundedSource[];
  /** Digest of the submission's reference sources; empty for unsourced briefs. */
  evidenceSummary?: string;
  /** Rotated per section so legacy articles cite more than one source. */
  preferredEvidenceUrl?: string;
  keywords: string[];
  /**
   * BlogInput.focusKeyword. The article contract requires it verbatim in the
   * introduction, and the intro is written as its own section here, so the
   * requirement has to travel with the section context.
   */
  focusKeyword?: string;
  /** Resolved editorial policy - see shared/editorial-policy.ts. */
  policy?: EditorialPolicy;
  /** Brief requirements with no column of their own - see shared/brief.ts. */
  briefDirectives?: string[];
  /** generationConfig.maxSectionRetries - attempts per section (default 2). */
  maxSectionRetries?: number;
  /** BlogInput.tone - professional | casual | technical. */
  tone?: string;
  /** BlogInput.contentLength - the editor's target word count for the article. */
  targetWords?: number;
  /** Binding article-wide range from the brief. */
  /** Full submission specs (writingInstructions, internalLinks, etc.) */
  specs?: Record<string, unknown>;
  internalLinks?: string[];
  writingInstructions?: string[];
  mustFollow?: string[];
};

